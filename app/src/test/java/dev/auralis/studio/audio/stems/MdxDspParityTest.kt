package dev.auralis.studio.audio.stems

import kotlin.math.PI
import kotlin.math.abs
import kotlin.math.sin
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class MdxDspParityTest {
    @Test fun `Voc FT contract cannot regress to 9482 dimensions`() {
        assertEquals(44_100, VocFtContract.SAMPLE_RATE_HZ)
        assertEquals(256, VocFtContract.DIM_T)
        assertEquals(1_024, VocFtContract.HOP)
        assertEquals(3_072, VocFtContract.DIM_F)
        assertEquals(6_144, VocFtContract.N_FFT)
        assertArrayEquals(setOf(StemKind.VOCALS, StemKind.INSTRUMENTAL).toTypedArray(), VocFtModel.descriptor.supportedStems.toTypedArray())
        assertEquals(66_848_828L, VocFtModel.descriptor.modelBytes)
        assertEquals("5ef47e3b3bafa14357532c0a3f6c5f18444d94b6efe3fd62b3d13f80051f1e58", VocFtModel.descriptor.modelSha256)
    }

    @Test fun `Kotlin STFT plane packing matches upstream NumPy oracle`() {
        val left = FloatArray(VocFtContract.CHUNK_SIZE) { index ->
            (0.35 * sin(2.0 * PI * 440.0 * index / 44_100.0) +
                0.10 * sin(2.0 * PI * 1_234.0 * index / 44_100.0)).toFloat()
        }
        val right = FloatArray(VocFtContract.CHUNK_SIZE) { index ->
            (0.25 * sin(2.0 * PI * 880.0 * index / 44_100.0 + 0.3)).toFloat()
        }
        val spectrum = VocFtStft().transform(left, right)
        // Values generated by gyoom-sa/UVR-MDX-LiteRT separate.py's NumPy STFT.
        assertOracle(spectrum, 0, 0, 0, 12.2977877f)
        assertOracle(spectrum, 0, 61, 37, -66.2633286f)
        assertOracle(spectrum, 1, 61, 37, 502.628418f)
        assertOracle(spectrum, 2, 123, 101, 295.415192f)
        assertOracle(spectrum, 3, 123, 101, 180.560287f)
        assertOracle(spectrum, 0, 3_071, 255, -0.00858665351f, 2e-5f)
    }

    @Test fun `STFT inverse reconstructs stereo without swap or phase inversion`() {
        val left = FloatArray(VocFtContract.CHUNK_SIZE) { index ->
            (0.31 * sin(2.0 * PI * 330.0 * index / 44_100.0)).toFloat()
        }
        val right = FloatArray(VocFtContract.CHUNK_SIZE) { index ->
            (0.19 * sin(2.0 * PI * 1_420.0 * index / 44_100.0 + 0.4)).toFloat()
        }
        val reconstructed = VocFtIstft().inverse(VocFtStft().transform(left, right))
        var leftError = 0.0
        var rightError = 0.0
        var swappedError = 0.0
        for (index in left.indices) {
            leftError += (left[index] - reconstructed.left[index]).let { it * it }
            rightError += (right[index] - reconstructed.right[index]).let { it * it }
            swappedError += (left[index] - reconstructed.right[index]).let { it * it }
        }
        val rmsLeft = kotlin.math.sqrt(leftError / left.size)
        val rmsRight = kotlin.math.sqrt(rightError / right.size)
        assertTrue("left RMS error $rmsLeft", rmsLeft < 2e-5)
        assertTrue("right RMS error $rmsRight", rmsRight < 2e-5)
        assertTrue("channels appear swapped", swappedError > leftError * 100.0)
    }

    private fun assertOracle(
        spectrum: FloatArray,
        plane: Int,
        bin: Int,
        frame: Int,
        expected: Float,
        absoluteTolerance: Float = maxOf(2e-4f, abs(expected) * 2e-5f),
    ) {
        assertEquals(expected, spectrum[VocFtContract.tensorIndex(plane, bin, frame)], absoluteTolerance)
    }
}
